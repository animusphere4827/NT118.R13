CREATE TABLE course_units (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(80) NOT NULL UNIQUE,
  title VARCHAR(200) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  position INTEGER NOT NULL UNIQUE CHECK (position > 0),
  status VARCHAR(10) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED'))
);

CREATE TABLE course_lessons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  unit_id INTEGER NOT NULL REFERENCES course_units(id) ON DELETE CASCADE,
  seed_key VARCHAR(100) NOT NULL UNIQUE,
  title VARCHAR(200) NOT NULL,
  subtitle TEXT NOT NULL DEFAULT '',
  type VARCHAR(20) NOT NULL CHECK (type IN ('VOCABULARY','GRAMMAR','PRACTICE_PART5','READING','MOCK_TEST')),
  minutes INTEGER NOT NULL CHECK (minutes BETWEEN 1 AND 240),
  position INTEGER NOT NULL CHECK (position > 0),
  status VARCHAR(10) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED')),
  vocabulary_topic_id INTEGER REFERENCES vocabulary_topics(id),
  grammar_lesson_id INTEGER REFERENCES grammar_lessons(id),
  practice_set_id INTEGER REFERENCES practice_sets(id),
  reading_group_id INTEGER REFERENCES question_groups(id),
  mock_test_id INTEGER REFERENCES mock_tests(id),
  UNIQUE (unit_id, position),
  CHECK (
    num_nonnulls(vocabulary_topic_id,grammar_lesson_id,practice_set_id,reading_group_id,mock_test_id)=1
    AND CASE type
      WHEN 'VOCABULARY' THEN vocabulary_topic_id IS NOT NULL
      WHEN 'GRAMMAR' THEN grammar_lesson_id IS NOT NULL
      WHEN 'PRACTICE_PART5' THEN practice_set_id IS NOT NULL
      WHEN 'READING' THEN reading_group_id IS NOT NULL
      WHEN 'MOCK_TEST' THEN mock_test_id IS NOT NULL
      ELSE FALSE
    END
  )
);

CREATE TABLE user_reading_progress (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  group_id INTEGER NOT NULL REFERENCES question_groups(id) ON DELETE CASCADE,
  completed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id,group_id)
);

CREATE INDEX idx_practice_questions_question ON practice_set_questions(question_id,practice_set_id);
CREATE INDEX idx_practice_submitted_content ON practice_attempts(user_id,practice_set_id) WHERE status='SUBMITTED';
CREATE INDEX idx_mock_submitted_content ON mock_test_attempts(user_id,mock_test_id) WHERE status='SUBMITTED';

CREATE VIEW published_readings AS
SELECT g.id,g.part_id,g.title,g.instructions,
  COUNT(p.id)::integer AS passage_count,
  array_agg(DISTINCT p.passage_type ORDER BY p.passage_type) AS passage_types
FROM question_groups g
JOIN reading_passages p ON p.group_id=g.id
WHERE EXISTS (
  SELECT 1 FROM questions q
  JOIN practice_set_questions link ON link.question_id=q.id
  JOIN practice_sets s ON s.id=link.practice_set_id
  WHERE q.group_id=g.id AND q.status='PUBLISHED' AND s.status='PUBLISHED'
    AND q.part_id=g.part_id AND s.part_id=g.part_id
)
GROUP BY g.id;
