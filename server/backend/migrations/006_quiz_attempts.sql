CREATE TABLE quiz_sets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(80) NOT NULL UNIQUE,
  title VARCHAR(200) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  vocabulary_topic_id INTEGER REFERENCES vocabulary_topics(id),
  grammar_lesson_id INTEGER REFERENCES grammar_lessons(id),
  time_limit INTEGER NOT NULL DEFAULT 600 CHECK (time_limit BETWEEN 60 AND 7200),
  status VARCHAR(10) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED')),
  CHECK (num_nonnulls(vocabulary_topic_id,grammar_lesson_id)<=1)
);

CREATE TABLE quiz_questions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quiz_set_id INTEGER NOT NULL REFERENCES quiz_sets(id) ON DELETE CASCADE,
  position INTEGER NOT NULL CHECK (position BETWEEN 1 AND 50),
  type VARCHAR(20) NOT NULL CHECK (type IN ('FILL_BLANK','MATCH','ORDER')),
  prompt TEXT NOT NULL,
  payload JSONB NOT NULL CHECK (jsonb_typeof(payload)='object'),
  solution JSONB NOT NULL CHECK (jsonb_typeof(solution)='object'),
  explanation TEXT NOT NULL,
  UNIQUE (quiz_set_id,position)
);

CREATE TABLE quiz_attempts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  quiz_set_id INTEGER NOT NULL REFERENCES quiz_sets(id),
  content_title VARCHAR(200) NOT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'IN_PROGRESS' CHECK (status IN ('IN_PROGRESS','SUBMITTED')),
  total_questions INTEGER NOT NULL CHECK (total_questions BETWEEN 1 AND 50),
  correct_count INTEGER,
  accuracy NUMERIC(5,2),
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  deadline_at TIMESTAMPTZ NOT NULL,
  submitted_at TIMESTAMPTZ,
  result JSONB
);

CREATE TABLE quiz_answers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id INTEGER NOT NULL REFERENCES quiz_attempts(id) ON DELETE CASCADE,
  question_id INTEGER NOT NULL REFERENCES quiz_questions(id),
  position INTEGER NOT NULL,
  snapshot JSONB NOT NULL,
  answer JSONB,
  is_correct BOOLEAN,
  answered_at TIMESTAMPTZ,
  UNIQUE (attempt_id,question_id),
  UNIQUE (attempt_id,position)
);

CREATE INDEX idx_quiz_attempts_user ON quiz_attempts(user_id,started_at DESC,id DESC);
CREATE INDEX idx_quiz_attempts_expired ON quiz_attempts(deadline_at) WHERE status='IN_PROGRESS';

