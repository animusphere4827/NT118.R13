CREATE TABLE course_vocabulary_progress (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  lesson_id INTEGER NOT NULL REFERENCES course_lessons(id) ON DELETE CASCADE,
  words JSONB NOT NULL CHECK (jsonb_typeof(words)='array' AND jsonb_array_length(words)>0),
  passed_count INTEGER NOT NULL DEFAULT 0 CHECK (passed_count>=0 AND passed_count<=jsonb_array_length(words)),
  studied_ids INTEGER[] NOT NULL DEFAULT '{}',
  completed_at TIMESTAMPTZ,
  source VARCHAR(10) NOT NULL DEFAULT 'CHECK' CHECK (source IN ('CHECK','LEGACY')),
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(user_id,lesson_id),
  CHECK ((completed_at IS NOT NULL)=(passed_count=jsonb_array_length(words)))
);

CREATE TABLE vocabulary_lesson_checks (
  id UUID PRIMARY KEY,
  progress_id INTEGER NOT NULL REFERENCES course_vocabulary_progress(id) ON DELETE CASCADE,
  batch_start INTEGER NOT NULL CHECK (batch_start>=0),
  questions JSONB NOT NULL CHECK (jsonb_typeof(questions)='array' AND jsonb_array_length(questions) BETWEEN 1 AND 10),
  answers JSONB,
  result JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  submitted_at TIMESTAMPTZ,
  CHECK ((submitted_at IS NULL)=(result IS NULL)),
  CHECK ((submitted_at IS NULL)=(answers IS NULL))
);
CREATE UNIQUE INDEX idx_vocabulary_check_active ON vocabulary_lesson_checks(progress_id) WHERE submitted_at IS NULL;
CREATE INDEX idx_vocabulary_checks_progress ON vocabulary_lesson_checks(progress_id,created_at DESC);

INSERT INTO course_vocabulary_progress(user_id,lesson_id,words,passed_count,completed_at,source)
SELECT p.user_id,l.id,
  jsonb_agg(jsonb_build_object('id',v.id,'word',v.word,'meaning_vi',v.meaning_vi,
    'ipa',v.ipa,'part_of_speech',v.part_of_speech,'example_sentence',v.example_sentence,
    'audio_url',v.audio_url,'image_url',v.image_url) ORDER BY v.id),
  count(*)::integer,now(),'LEGACY'
FROM course_lessons l
JOIN vocabularies v ON v.topic_id=l.vocabulary_topic_id AND v.status='PUBLISHED'
JOIN user_vocabulary_progress p ON p.vocabulary_id=v.id
WHERE l.type='VOCABULARY'
GROUP BY p.user_id,l.id,l.vocabulary_topic_id
HAVING bool_and(p.status='MASTERED') AND count(*)=(
  SELECT count(*) FROM vocabularies all_words
  WHERE all_words.topic_id=l.vocabulary_topic_id AND all_words.status='PUBLISHED'
);
